import DOMPurify from "isomorphic-dompurify";

const allowedTags = [
  "p",
  "br",
  "strong",
  "em",
  "u",
  "s",
  "h1",
  "h2",
  "h3",
  "h4",
  "h5",
  "h6",
  "ul",
  "ol",
  "li",
  "blockquote",
  "a",
  "hr",
  "figure",
  "figcaption",
  "img",
  "table",
  "thead",
  "tbody",
  "tr",
  "th",
  "td",
  "pre",
  "code",
  "section",
  "div",
  "span",
];

export function sanitizeCmsHtml(value: string) {
  return DOMPurify.sanitize(value, {
    ALLOWED_TAGS: allowedTags,
    ALLOWED_ATTR: [
      "href",
      "src",
      "alt",
      "title",
      "width",
      "height",
      "colspan",
      "rowspan",
      "data-besat-block",
      "data-media",
      "class",
      "dir",
    ],
    ALLOW_DATA_ATTR: false,
  });
}
